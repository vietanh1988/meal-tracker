VARS = {"ten", "so_ngay", "cap", "ml", "so_nhiem_vu", "kcal_con_lai", "x", "y"}

def main():
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    lp = os.path.join(root, "src", "pi", "chatLines.json")
    voiced = set(json.load(open(os.path.join(root, "src", "pi", "voice.json"), encoding="utf-8"))["ids"])
    d = json.load(open(lp, encoding="utf-8"))
    ids = {c["id"] for g in d["nhom"] for c in g["cau"]}
    bad = [k for k in L if k not in ids or k in voiced or k.startswith("BUON")]
    assert not bad, f"không được viết lại: {bad}"
    for k, (nam, nu) in L.items():
        for t in (nam, nu):
            vs = set(re.findall(r"\{([a-z_]+)\}", t)); assert vs <= VARS, (k, vs - VARS)
            assert len(t) <= 110, (k, len(t), t)
    for g in d["nhom"]:
        for c in g["cau"]:
            if c["id"] in L: c["text"], c["nu"] = L[c["id"]]
    json.dump(d, open(lp, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    fp = os.path.join(os.path.dirname(os.path.abspath(__file__)), "chat_fix.json")
    fix = json.load(open(fp, encoding="utf-8"))
    for k, (nam, nu) in L.items(): fix[k] = {"text": nam, "nu": nu}
    fix["_ghi_chu_v2"] = "31/10 bộ câu bản 2 (scripts/pi/chat_v2.py): {text: Pi nam, nu: Pi nữ}. Giữ nguyên 20 câu có giọng + 4 câu BUON."
    json.dump(fix, open(fp, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(len(L), "câu × 2 bản; giữ nguyên", len(ids) - len(L), "câu")

if __name__ == "__main__": main()
